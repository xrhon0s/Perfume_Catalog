import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import vm from "node:vm"
import ts from "typescript"

const outputPath = resolve("supabase/seed.sql")
const omittedReportPath = resolve("supabase/omitted-perfumes.json")

function toSlug(text) {
  return text
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[’]/g, "'")
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
}

function sql(value) {
  if (value === undefined || value === null || value === "") {
    return "null"
  }

  return `'${String(value).replaceAll("'", "''")}'`
}

function sqlArray(values = []) {
  if (!values.length) return "'{}'::text[]"
  return `array[${values.map(sql).join(", ")}]::text[]`
}

function sqlJson(value) {
  if (!value || Object.keys(value).length === 0) {
    return "'{}'::jsonb"
  }

  return `${sql(JSON.stringify(value))}::jsonb`
}

function loadTsModule(filePath) {
  const source = readFileSync(filePath, "utf8")
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
    },
  }).outputText

  const exports = {}
  const context = {
    exports,
    require: () => ({}),
  }

  vm.runInNewContext(compiled, context, { filename: filePath })
  return exports
}

const { perfumeDb } = loadTsModule(resolve("src/data/legacy/perfumeDb.ts"))
const { perfumeDetails } = loadTsModule(resolve("src/data/legacy/perfumeDetails.ts"))
const perfumeBaseById = new Map(perfumeDb.map((perfume) => [perfume.id, perfume]))
const missingBasePerfumes = Object.keys(perfumeDetails).filter(
  (id) => !perfumeBaseById.has(id),
)

if (missingBasePerfumes.length > 0) {
  throw new Error(
    `perfumeDetails has records without perfumeDb base rows: ${missingBasePerfumes.join(", ")}`,
  )
}

const perfumes = Object.entries(perfumeDetails).map(([id, details]) => ({
  ...perfumeBaseById.get(id),
  ...details,
}))
const omittedPerfumes = perfumeDb.filter((perfume) => !perfumeDetails[perfume.id])
const brands = Array.from(new Set(perfumes.map((perfume) => perfume.brand))).sort(
  (a, b) => a.localeCompare(b),
)
const slugKeys = perfumes.map((perfume) => `${perfume.brand}::${toSlug(perfume.name)}`)
const duplicateSlugKeys = new Set(
  slugKeys.filter((key, index) => slugKeys.indexOf(key) !== index),
)

function perfumeSlug(perfume) {
  const baseSlug = toSlug(perfume.name)
  const slugKey = `${perfume.brand}::${baseSlug}`

  if (!duplicateSlugKeys.has(slugKey)) {
    return baseSlug
  }

  return `${baseSlug}-${toSlug(perfume.id)}`
}

const lines = [
  "-- Generated by npm run seed:catalog",
  "-- Load this file after running supabase/migrations/001_catalog_inventory.sql",
  "",
  "begin;",
  "",
  "insert into public.brands (name, slug)",
  "values",
  brands
    .map((brand, index) => {
      const suffix = index === brands.length - 1 ? "" : ","
      return `  (${sql(brand)}, ${sql(toSlug(brand))})${suffix}`
    })
    .join("\n"),
  "on conflict (slug) do update set",
  "  name = excluded.name;",
  "",
]

for (const perfume of perfumes) {
  const brandSlug = toSlug(perfume.brand)
  const uniquePerfumeSlug = perfumeSlug(perfume)

  lines.push(
    "insert into public.perfumes (",
    "  legacy_id, brand_id, name, slug, family, concentration, gender, year,",
    "  description, tags, notes, primary_image_url, primary_image_path, is_active",
    ")",
    "select",
    `  ${sql(perfume.id)}, b.id, ${sql(perfume.name)}, ${sql(uniquePerfumeSlug)},`,
    `  ${sql(perfume.family)}, ${sql(perfume.concentration)}, ${sql(perfume.gender)}, ${
      perfume.year ?? "null"
    },`,
    `  ${sql(perfume.description)}, ${sqlArray(perfume.tags)}, ${sqlJson(
      perfume.notes,
    )},`,
    `  ${sql(perfume.image)}, null, true`,
    "from public.brands b",
    `where b.slug = ${sql(brandSlug)}`,
    "on conflict (legacy_id) do update set",
    "  brand_id = excluded.brand_id,",
    "  name = excluded.name,",
    "  slug = excluded.slug,",
    "  family = excluded.family,",
    "  concentration = excluded.concentration,",
    "  gender = excluded.gender,",
    "  year = excluded.year,",
    "  description = excluded.description,",
    "  tags = excluded.tags,",
    "  notes = excluded.notes,",
    "  primary_image_url = excluded.primary_image_url,",
    "  primary_image_path = excluded.primary_image_path,",
    "  is_active = excluded.is_active;",
    "",
  )
}

lines.push("commit;", "")

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, lines.join("\n"))
writeFileSync(
  omittedReportPath,
  `${JSON.stringify(
    omittedPerfumes.map((perfume) => ({
      id: perfume.id,
      name: perfume.name,
      brand: perfume.brand,
    })),
    null,
    2,
  )}\n`,
)

console.log(`Wrote ${outputPath}`)
console.log(`Wrote ${omittedReportPath}`)
console.log(`Seed includes ${perfumes.length} enriched perfumes and ${brands.length} brands.`)
console.log(`Omitted ${omittedPerfumes.length} perfumes without perfumeDetails records.`)
